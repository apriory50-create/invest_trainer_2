List<MarketScenario> _build100Scenarios() {
  final List<MarketScenario> list = [];
  int id = 1;

  for (final c in _baseCases) {
    list.add(
      MarketScenario(
        id: id,
        title: 'Сценарий #$id: ${c.title}',
        ticker: c.ticker,
        description: c.desc,
        options: c.opts,
        correctIndex: c.ans,
        explanation: c.exp,
        priceChangePercent: c.delta,
      ),
    );
    id++;
  }

  const List<String> contexts = [
    'Квартальный отчет МСФО',
    'Внеочередное заседание ЦБ РФ',
    'Ребалансировка индекса Мосбиржи',
    'Решение Совета директоров по дивидендам',
    'Стресс-тест долгового рынка',
    'Сырьевой цикл и курс валют',
    'Налоговое планирование в конце декабря',
    'Оценка по 5 Фильтрам Профи',
    'Аудит кредитного качества портфеля',
    'Управление риском на волатильном рынке',
  ];

  int ctxIdx = 0;
  while (list.length < 100) {
    for (final tpl in _dynamicTemplates) {
      if (list.length >= 100) break;
      final ctx = contexts[ctxIdx % contexts.length];
      final int correctPos = id % 3;
      final List<String> opts = [];
      if (correctPos == 0) {
        opts.addAll([tpl['good']!, tpl['bad1']!, tpl['bad2']!]);
      } else if (correctPos == 1) {
        opts.addAll([tpl['bad1']!, tpl['good']!, tpl['bad2']!]);
      } else {
        opts.addAll([tpl['bad1']!, tpl['bad2']!, tpl['good']!]);
      }

      list.add(
        MarketScenario(
          id: id,
          title: 'Сценарий #$id ($ctx): ${tpl['t']}',
          ticker: tpl['tk']!,
          description:
              'Кейс [$ctx]. На рынке возникла ситуация: ${tpl['t']}. Выбери профессиональное решение, которое защитит и приумножит твой портфель.',
          options: opts,
          correctIndex: correctPos,
          explanation: tpl['exp']!,
          priceChangePercent: 3.5 + (id % 5),
        ),
      );
      id++;
    }
    ctxIdx++;
  }

  return list;
}

final List<MarketScenario> marketScenarios = _build100Scenarios();

